import numpy as np
from pathlib import Path
import joblib
from sklearn.ensemble import IsolationForest
from sklearn.metrics import confusion_matrix, precision_score, recall_score, f1_score
FEATURES=['packet_rate','response_ms','cpu_pct','memory_pct','failed_requests','connection_frequency','bytes_sent','session_seconds','reconnections','error_frequency']

def synthetic_data(n=800, seed=42):
    rng=np.random.default_rng(seed); normal=np.column_stack([rng.normal(40,8,n),rng.normal(35,8,n),rng.normal(30,10,n),rng.normal(45,10,n),rng.poisson(0.4,n),rng.normal(3,1,n),rng.normal(18000,4000,n),rng.normal(300,70,n),rng.poisson(.2,n),rng.poisson(.5,n)])
    normal[:,[0,2,3,5,6,7]]=np.maximum(normal[:,[0,2,3,5,6,7]],0); normal[:,[2,3]]=np.clip(normal[:,[2,3]],0,100)
    abnormal=np.column_stack([rng.normal(125,20,n//4),rng.normal(180,35,n//4),rng.normal(88,8,n//4),rng.normal(90,7,n//4),rng.poisson(8,n//4),rng.normal(12,3,n//4),rng.normal(90000,15000,n//4),rng.normal(50,15,n//4),rng.poisson(5,n//4),rng.poisson(7,n//4)])
    abnormal=np.maximum(abnormal,0); abnormal[:,[2,3]]=np.clip(abnormal[:,[2,3]],0,100)
    return normal, abnormal

def evaluate(seed=42):
    normal, abnormal=synthetic_data(800,seed); rng=np.random.default_rng(seed); rng.shuffle(normal); rng.shuffle(abnormal)
    train=normal[:600]; x=np.vstack([normal[600:],abnormal]); y=np.array([0]*len(normal[600:])+[1]*len(abnormal))
    model=IsolationForest(n_estimators=150,contamination=0.2,random_state=seed); model.fit(train); pred=(model.predict(x)==-1).astype(int)
    tn,fp,fn,tp=confusion_matrix(y,pred,labels=[0,1]).ravel()
    return {'model':'IsolationForest','seed':seed,'training_samples':len(train),'test_samples':len(x),'features':FEATURES,'true_positive':int(tp),'true_negative':int(tn),'false_positive':int(fp),'false_negative':int(fn),'precision':float(precision_score(y,pred,zero_division=0)),'recall':float(recall_score(y,pred,zero_division=0)),'f1':float(f1_score(y,pred,zero_division=0)),'detection_rate':float(tp/max(tp+fn,1)),'false_positive_rate':float(fp/max(fp+tn,1)),'note':'Synthetic benchmark; metrics describe this generated dataset only.'}

def infer(sample: dict):
    missing=set(FEATURES)-set(sample)
    if missing: raise ValueError('Missing features: '+', '.join(sorted(missing)))
    values=np.array([[float(sample[f]) for f in FEATURES]])
    if not np.isfinite(values).all() or (values<0).any(): raise ValueError('Features must be finite non-negative numbers')
    model_path=Path(__file__).resolve().parents[2]/'data'/'generated'/'isolation_forest.joblib'
    if model_path.exists():
        # Only load the model artifact generated by this project's own training script. Never load user uploads.
        model=joblib.load(model_path); normal,_=synthetic_data(1000,42)
    else:
        normal,_=synthetic_data(1000,42); model=IsolationForest(n_estimators=150,contamination=.05,random_state=42).fit(normal)
    pred=int(model.predict(values)[0]); score=float(model.decision_function(values)[0]); reasons=[]
    for f,v in sample.items():
        mu=float(normal[:,FEATURES.index(f)].mean()); sd=float(normal[:,FEATURES.index(f)].std() or 1)
        if abs(float(v)-mu)>2.5*sd: reasons.append({'feature':f,'value':float(v),'baseline_mean':round(mu,2),'deviation_sigma':round(abs(float(v)-mu)/sd,2)})
    return {'classification':'Anomalous' if pred==-1 else 'Normal','decision_score':score,'model':'IsolationForest / synthetic-baseline-v1','unusual_features':reasons,'synthetic':True}


def train_model(seed=42):
    normal, _ = synthetic_data(800, seed)
    model = IsolationForest(n_estimators=150, contamination=0.05, random_state=seed)
    model.fit(normal[:600])
    return model
